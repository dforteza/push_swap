#include "push_swap.h"

int	is_sorted(t_node *stack)
{
	if (!stack)
		return (1);
	while (stack->next)
	{
		if (stack->index > stack->next->index)
			return (0);
		stack = stack->next;
	}
	return (1);
}

int	has_two(t_node *stack)
{
	if (stack == NULL || stack->next == NULL)
		return (0);
	return (1);
}
